#!/usr/bin/env python3
"""Keeps Localization/*.lproj in step with the L("...") keys used in Sources/Stash.

- en.lproj is generated (keys are the English text).
- tr.lproj is hand-written; missing keys are listed and the script exits non-zero.
Usage: python3 scripts/sync-strings.py
"""
import glob, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
keys = []
for path in sorted(glob.glob(str(root / "Sources/Stash/**/*.swift"), recursive=True)):
    text = open(path, encoding="utf-8").read()
    # L("..."), Shortcuts' LocalizedStringResource("...") and parameter summaries (\(\.$files) → ${files}).
    for m in re.finditer(r'\b(?:L|LocalizedStringResource|Summary)\("((?:[^"\\]|\\.)*?)"(?=[,)\s])', text):
        key = re.sub(r'\\\(\\\.\$(\w+)\)', r'${\1}', m.group(1))
        if key not in keys:
            keys.append(key)

def parse(path):
    out = {}
    if not path.exists():
        return out
    for m in re.finditer(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', path.read_text(encoding="utf-8"), re.M):
        out[m.group(1)] = m.group(2)
    return out

en = root / "Localization/en.lproj/Localizable.strings"
en.parent.mkdir(parents=True, exist_ok=True)
en.write_text("/* Generated by scripts/sync-strings.py — keys are the English text. */\n\n" +
              "".join(f'"{k}" = "{k}";\n' for k in keys), encoding="utf-8")

tr = parse(root / "Localization/tr.lproj/Localizable.strings")
missing = [k for k in keys if k not in tr]
unused = [k for k in tr if k not in keys]
for k in missing:
    print(f'missing tr: "{k}"')
for k in unused:
    print(f'unused tr: "{k}"')
print(f"{len(keys)} keys, {len(missing)} missing, {len(unused)} unused")
sys.exit(1 if missing else 0)
